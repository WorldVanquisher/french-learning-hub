"""Write a hash-locked requirements file from a ``pip install --dry-run --report`` file.

  # resolve inside the pinned base image, constrained to the versions to keep:
  docker run --rm -v $PWD/tools/speaking:/s:ro -v $OUT:/out python:3.12-slim@sha256:6c4dd321… \\
      pip install --dry-run --ignore-installed --report /out/report.json \\
      [--index-url https://download.pytorch.org/whl/cpu --extra-index-url https://pypi.org/simple] \\
      -c /s/requirements-cpu.lock -r /s/requirements.txt
  python3 -I -B tools/speaking/scripts/lock_from_report.py $OUT/report.json VARIANT > tools/speaking/requirements-VARIANT.lock

Every resolved distribution becomes ``name==version --hash=sha256:...``, sorted by
name, so ``pip install --require-hashes --no-deps -r`` installs exactly that set.
"""

from __future__ import annotations

import sys

sys.dont_write_bytecode = True

import json  # noqa: E402


def main() -> int:
    report, variant = sys.argv[1], sys.argv[2]
    with open(report, encoding="utf-8") as fh:
        doc = json.load(fh)
    lines = []
    for item in doc["install"]:
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        hashes = (item.get("download_info", {}).get("archive_info") or {}).get("hashes") or {}
        if "sha256" not in hashes:
            raise SystemExit(f"{name}=={version}: the report has no sha256")
        url = item["download_info"]["url"]
        lines.append((name.lower(), f"{name}=={version} --hash=sha256:{hashes['sha256']}", url.split("/")[-1]))
    print(f"# Hash-locked install set for the {variant} image (tools/speaking/Dockerfile), generated by")
    print("# scripts/lock_from_report.py from a pip resolution report; regenerate it rather than editing it.")
    for _, line, wheel in sorted(lines):
        print(f"{line}  # {wheel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
