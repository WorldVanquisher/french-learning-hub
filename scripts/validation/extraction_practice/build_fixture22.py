#!/usr/bin/env python3
"""Build (or check) the workbench's copy of the SEALED Extraction 2.2 Workbooks bundle (feeds only).

    python3 -I -B scripts/validation/extraction_practice/build_fixture22.py --handoff H22 [--check]

H22 is the extraction lane's sealed handoff-2.2. Its SHA256SUMS and the bundle's own
(`sample/workbooks2/SHA256SUMS`) must verify first. The five `flh_practice_review_feed_v1` feeds
with the 2.2 additions (`flh_practice_feed_additions_v1`), the replay cases and the compatibility
report are copied byte for byte, each with its SHA-256, into
web/src/prototype/extraction22Fixture.ts. The page and the tests re-hash them before use. Exit 0
written or up to date; 1 differs (--check); 3 a seal fails.
"""
import hashlib
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sealed_extraction as se  # noqa: E402

REPO = se.REPO
OUT = REPO / "web/src/prototype/extraction22Fixture.ts"
BUNDLE = "sample/workbooks2"
NAMES = ["feed-1-r1.json", "feed-2-r1-newly-approved.json", "feed-3-r2-withdrawn.json", "feed-4-r3-awaiting-confirmation.json", "feed-5-r3-restored.json",
         "replay-cases.json", "compat-report.json"]


def render(h: Path, digest: str) -> str:
    docs = []
    for n in NAMES:
        raw = (h / BUNDLE / n).read_bytes()
        docs.append({"name": n, "path": f"{BUNDLE}/{n}", "sha256": hashlib.sha256(raw).hexdigest(), "text": raw.decode("utf-8")})
    src = {"owner": "extraction lane (Extraction 2.2 prototype, HANDOFF-2.2)", "handoff": "extraction2-20261119/handoff-2.2", "handoff_sha256sums": digest,
           "bundle": BUNDLE, "contract_additions": "flh_practice_feed_additions_v1", "synthetic": True}
    return ("// GENERATED by scripts/validation/extraction_practice/build_fixture22.py --handoff <handoff-2.2>: do not edit.\n"
            "// The extraction lane's SEALED Extraction 2.2 Workbooks feeds (synthetic), each with its SHA-256.\n\n"
            "export const FIXTURE22_SOURCE = " + json.dumps(src, ensure_ascii=False, indent=1, sort_keys=True) + " as const;\n\n"
            "export const FIXTURE22_DOCUMENTS: readonly { name: string; path: string; sha256: string; text: string }[] = "
            + json.dumps(docs, ensure_ascii=False, indent=1) + ";\n")


def main():
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    if len(args) != 2 or args[0] != "--handoff":
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 2
    h = Path(os.path.realpath(args[1]))
    try:
        digest = se.verify_sums(h)
        se.verify_sums(h / BUNDLE)
        outer = se.read_sums(h / "SHA256SUMS")
        for n in NAMES:
            if f"{BUNDLE}/{n}" not in outer:
                raise se.SealError(f"the handoff seal does not cover {BUNDLE}/{n}")
    except se.SealError as e:
        print(f"REFUSED: {e}", file=sys.stderr)
        return 3
    text = render(h, digest)
    print(f"handoff-2.2 SHA256SUMS {digest}; {len(NAMES)} documents")
    if check:
        same = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("fixture module up to date" if same else "fixture module differs from the sealed sources")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
