import type { ExplanationVariants } from "./learning";

// GET /vocabulary (vocabulary_v1): the learner's private saved terms. A saved
// term is a Knowledge Concept (its durable identity), never text; its examples
// are approved units with the record and extraction they came from.

export interface VocabularyConcept {
  id: number;
  target: string;
  pedagogical_intent: string;
  scope: string;
  identity_features: Record<string, string>;
  state: "active" | "orphaned" | "retired";
}

export interface VocabularySource {
  entry_id: number;
  original_input: string; // the learner's own words, exactly as written
  original_context: string;
  created_at: string;
}

export interface VocabularyExample {
  unit_id: number;
  entry_id: number;
  extraction_id: number;
  extraction_version: number;
  saved_at: string;
  // current: the unit still supports the Concept; not_current: a newer
  // extraction, an admission change or a reassignment; missing: unreadable.
  status: "current" | "not_current" | "missing";
  newer_extraction: boolean;
  // Generated by the extraction (`extractor` names it); null when unreadable.
  term: string | null;
  kind: string | null;
  meaning: string | null;
  meanings: ExplanationVariants; // en / zh: null when that language was not recorded
  sentence: string | null;
  extractor: string | null;
  source: VocabularySource | null;
}

export interface VocabularyItem {
  concept_id: number;
  saved: boolean;
  saved_at: string;
  first_saved_at: string;
  concept: VocabularyConcept | null; // null when the Concept cannot be read
  review_units: number; // current supporting units: what Recall Practice can offer
  examples: VocabularyExample[];
}

export interface VocabularyList {
  schema_version: "vocabulary_v1";
  rule: string;
  query: string;
  tokens: string[];
  saved: number; // every saved term, before the query
  items: VocabularyItem[];
}

export interface VocabularySaveResult {
  item: VocabularyItem;
  changed: boolean;
  saved_now: boolean;
  example_added: boolean;
}

export interface VocabularyRemoveResult {
  concept_id: number;
  saved: boolean;
  changed: boolean;
}
