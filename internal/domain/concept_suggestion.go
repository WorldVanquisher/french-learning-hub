// SuggestionStaleReason names a change since generation that blocks
// confirmation.
type SuggestionStaleReason string

const (
	StaleUnitNotCurrentExtraction SuggestionStaleReason = "unit_not_in_current_extraction"
	StaleUnitHasCurrentSame       SuggestionStaleReason = "unit_has_current_same"
	StaleUnitInvalid              SuggestionStaleReason = "unit_invalid"
	StaleTargetRetired            SuggestionStaleReason = "target_retired"
	StaleTargetIdentityChanged    SuggestionStaleReason = "target_identity_changed"
	StaleTargetDistinctRecorded   SuggestionStaleReason = "target_distinct_recorded"
)

// SuggestionStaleError reports why a confirmation was refused. It wraps
// ErrConceptConflict, so callers treat it as a 409.
type SuggestionStaleError struct {
	Reasons []SuggestionStaleReason
}

func (e *SuggestionStaleError) Error() string {
	parts := make([]string, len(e.Reasons))
	for i, r := range e.Reasons {
		parts[i] = string(r)
	}
	return "suggestion is stale: " + strings.Join(parts, ", ")
}

func (e *SuggestionStaleError) Unwrap() error { return ErrConceptConflict }

// ---- provider contract ----

// SuggestionMemberExample is one current SAME member's wording, shown to the
// provider so a terse Concept identity is understandable.
type SuggestionMemberExample struct {
	Canonical string `json:"canonical"`
	Statement string `json:"statement"`
}

// SuggestionConceptInput is one candidate Concept as supplied to the provider.
type SuggestionConceptInput struct {
	ConceptID         int64                     `json:"concept_id"`
	Target            string                    `json:"target"`
	PedagogicalIntent string                    `json:"pedagogical_intent"`
	Scope             string                    `json:"scope"`
	IdentityFeatures  map[string]string         `json:"identity_features"`
	MemberExamples    []SuggestionMemberExample `json:"member_examples"`
}

// TextChars is the Concept's supplied text size in characters.
func (c SuggestionConceptInput) TextChars() int {
	n := utf8.RuneCountInString(c.Target) + utf8.RuneCountInString(c.PedagogicalIntent) + utf8.RuneCountInString(c.Scope)
	for k, v := range c.IdentityFeatures {
		n += utf8.RuneCountInString(k) + utf8.RuneCountInString(v)
	}
	for _, m := range c.MemberExamples {
		n += utf8.RuneCountInString(m.Canonical) + utf8.RuneCountInString(m.Statement)
	}
	return n
}

// SuggestionUnitInput is one KnowledgeUnit and its candidates as supplied to
// the provider. Learner-derived text is untrusted model input.
type SuggestionUnitInput struct {
	UnitID     int64                    `json:"unit_id"`
	Kind       KnowledgeKind            `json:"kind"`
	Canonical  string                   `json:"canonical"`
	Statement  string                   `json:"statement"`
	Example    *string                  `json:"example"`
	Candidates []SuggestionConceptInput `json:"candidates"`
}

// TextChars is the unit's own text size in characters.
func (u SuggestionUnitInput) TextChars() int {
	n := utf8.RuneCountInString(u.Canonical) + utf8.RuneCountInString(u.Statement)
	if u.Example != nil {
		n += utf8.RuneCountInString(*u.Example)
	}
	return n
}

// SuggestionRequest is the bounded batch sent in one provider call. Every unit
// has at least one candidate.
type SuggestionRequest struct {
	Units []SuggestionUnitInput
}

// SuggestionProposal is one validated provider answer.
type SuggestionProposal struct {
	UnitID    int64
	Outcome   SuggestionOutcome
	ConceptID *int64
	Reason    string
}

// ConceptSuggester proposes, for each unit, one of its supplied candidates or
// none. It never stores anything and makes exactly one call per Suggest.
type ConceptSuggester interface {
	Name() string
	Suggest(ctx context.Context, req SuggestionRequest) ([]SuggestionProposal, error)
}

// ValidateSuggestionProposals checks provider output against the request:
// exactly one proposal per supplied unit, no foreign or duplicate unit, a
// Concept only for 'suggested' and only from that unit's candidates, and a
// non-empty bounded reason. Failures wrap ErrValidation and name IDs only.
// Proposals are returned in request order with trimmed reasons.
func ValidateSuggestionProposals(req SuggestionRequest, proposals []SuggestionProposal) ([]SuggestionProposal, error) {
	units := make(map[int64]SuggestionUnitInput, len(req.Units))
	for _, u := range req.Units {
		units[u.UnitID] = u
	}
	byUnit := make(map[int64]SuggestionProposal, len(proposals))
	for _, p := range proposals {
		u, ok := units[p.UnitID]
		if !ok {
			return nil, fmt.Errorf("%w: suggestion names unit %d, which was not supplied", ErrValidation, p.UnitID)
		}
		if _, dup := byUnit[p.UnitID]; dup {
			return nil, fmt.Errorf("%w: suggestion names unit %d more than once", ErrValidation, p.UnitID)
		}
		switch p.Outcome {
		case SuggestionSuggested:
			if p.ConceptID == nil {
				return nil, fmt.Errorf("%w: suggestion for unit %d has no concept", ErrValidation, p.UnitID)
			}
			found := false
			for _, c := range u.Candidates {
				if c.ConceptID == *p.ConceptID {
					found = true
				}
			}
			if !found {
				return nil, fmt.Errorf("%w: suggestion for unit %d names concept %d, which was not a supplied candidate", ErrValidation, p.UnitID, *p.ConceptID)
			}
		case SuggestionNoSuitableCandidate, SuggestionUncertain:
			if p.ConceptID != nil {
				return nil, fmt.Errorf("%w: outcome %s for unit %d must not name a concept", ErrValidation, p.Outcome, p.UnitID)
			}
		default:
			return nil, fmt.Errorf("%w: unknown outcome for unit %d", ErrValidation, p.UnitID)
		}
		p.Reason = strings.TrimSpace(p.Reason)
		if p.Reason == "" {
			return nil, fmt.Errorf("%w: suggestion for unit %d has no reason", ErrValidation, p.UnitID)
		}
		if utf8.RuneCountInString(p.Reason) > MaxSuggestionReasonChars {
			return nil, fmt.Errorf("%w: reason for unit %d exceeds %d characters", ErrValidation, p.UnitID, MaxSuggestionReasonChars)
		}
		byUnit[p.UnitID] = p
	}
	out := make([]SuggestionProposal, 0, len(req.Units))
	for _, u := range req.Units {
		p, ok := byUnit[u.UnitID]
		if !ok {
			return nil, fmt.Errorf("%w: no suggestion for unit %d", ErrValidation, u.UnitID)
		}
		out = append(out, p)
	}
	return out, nil
}

// ValidateSuggestionUnitIDs checks a generation request's unit list.
func ValidateSuggestionUnitIDs(ids []int64) error {
	if len(ids) == 0 {
		return fmt.Errorf("%w: unit_ids must name at least one unit", ErrValidation)
	}
	if len(ids) > MaxSuggestionUnits {
		return fmt.Errorf("%w: unit_ids may name at most %d units", ErrValidation, MaxSuggestionUnits)
	}
	seen := make(map[int64]bool, len(ids))
	for _, id := range ids {
		if id <= 0 {
			return fmt.Errorf("%w: unit_ids must be positive", ErrValidation)
		}
		if seen[id] {
			return fmt.Errorf("%w: unit %d is named more than once", ErrValidation, id)
		}
		seen[id] = true
	}
	return nil
}

