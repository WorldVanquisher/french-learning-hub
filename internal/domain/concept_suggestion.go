// SuggestionSourceUnit is a unit verified reviewable when the request was
// prepared, with the Concepts it has a recorded DISTINCT with.
type SuggestionSourceUnit struct {
	Unit               KnowledgeUnit
	EntryID            int64
	DistinctConceptIDs map[int64]bool
}

// ConceptSuggestionRepository stores advisory suggestions and performs the
// guarded confirmation. It never alters membership except through Confirm.
type ConceptSuggestionRepository interface {
	// SuggestionSourceUnits loads and checks each unit is reviewable now.
	SuggestionSourceUnits(ctx context.Context, unitIDs []int64) ([]SuggestionSourceUnit, error)
	// SuggestionCatalog returns every non-retired Concept (persisted fields
	// only; support is not derived), the candidate universe.
	SuggestionCatalog(ctx context.Context) ([]KnowledgeConcept, error)
	// ConceptMemberExamples returns up to n current SAME members' wording per
	// Concept (preferred unit first, then lowest unit id).
	ConceptMemberExamples(ctx context.Context, conceptIDs []int64, n int) (map[int64][]SuggestionMemberExample, error)
	CommitSuggestionRun(ctx context.Context, run NewSuggestionRun) (*ConceptSuggestionRun, bool, error)
	GetSuggestionRun(ctx context.Context, id int64) (*ConceptSuggestionRun, error)
	GetSuggestionRunByOperation(ctx context.Context, operationID string) (*ConceptSuggestionRun, error)
	ListSuggestionRuns(ctx context.Context, limit int) ([]ConceptSuggestionRun, error)
	// ConfirmSuggestion revalidates and records the human SAME atomically. It
	// returns the item (with derived state), the SAME event, and whether this
	// was a replay of an earlier confirmation.
	ConfirmSuggestion(ctx context.Context, itemID, conceptID int64) (*ConceptSuggestionItem, *UnitConceptLink, bool, error)
}

// SameUnitIDs reports whether two unit-id lists are identical in order.
func SameUnitIDs(a, b []int64) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// SuggestionConfirmationEvidence is the evidence of a confirmed suggestion's
// human SAME: provenance only, never a reason retrieval evaluation counts as
// human truth.
func SuggestionConfirmationEvidence(item ConceptSuggestionItem, generator string) string {
	b, err := json.Marshal(map[string]any{
		"reason":             ConceptSuggestionEvidenceReason,
		"resolver":           ConceptResolverVersion,
		"suggestion_item_id": item.ID,
		"suggestion_run_id":  item.RunID,
		"generator":          generator,
	})
	if err != nil {
		return "{}"
	}
	return string(b)
}
