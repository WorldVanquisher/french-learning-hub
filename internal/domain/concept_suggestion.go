// SuggestionOutcome is one unit's result inside a completed run.
type SuggestionOutcome string

const (
	SuggestionSuggested           SuggestionOutcome = "suggested"
	SuggestionNoSuitableCandidate SuggestionOutcome = "no_suitable_candidate"
	SuggestionUncertain           SuggestionOutcome = "uncertain"
	// SuggestionNoCandidates is decided locally: the candidate policy supplied
	// nothing, so the provider was not asked about this unit.
	SuggestionNoCandidates SuggestionOutcome = "no_candidates"
)

