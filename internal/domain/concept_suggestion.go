// FLH-097 AI-assisted Concept membership suggestions.
//
// A suggestion is ADVISORY evidence. It never writes membership, Concepts,
// judgments, distinctions, admission or preferred representation, and it is
// never a human label merely because it exists. Only an explicit human
// confirmation records a human SAME, through the existing membership path,
// after the current state has been revalidated in the same transaction.

const (
	// ConceptSuggestionPromptVersion versions the suggester's instruction and
	// output schema; it is part of the stored generator provenance.
	ConceptSuggestionPromptVersion = "concept_suggestion_v1"
	// ConceptSuggestionCandidatePolicy names how candidates are chosen: exact
	// identity-signature matches first, then BM25 over the non-retired catalog,
	// excluding Concepts the unit has a recorded DISTINCT with.
	ConceptSuggestionCandidatePolicy = "concept_suggestion_candidates_v1"
	// ConceptSuggestionEvidenceReason is the evidence reason of a human SAME
	// recorded by confirming a suggestion. It is deliberately not one of the
	// reasons retrieval evaluation classifies as human truth (FLH-097 §5).
	ConceptSuggestionEvidenceReason = "human_same_ai_suggestion"
)

// Explicit bounds. Oversized input is rejected, never silently truncated or
// dropped.
const (
	MaxSuggestionUnits             = 10
	SuggestionCandidatesPerUnit    = 5
	SuggestionMemberExamples       = 2
	MaxSuggestionUnitTextChars     = 1200
	MaxSuggestionConceptTextChars  = 800
	MaxSuggestionReasonChars       = 500
	MaxSuggestionRunsListed        = 50
	DefaultSuggestionRunsListLimit = 20
)

