// Vocabulary (private workbench, Workbooks; never on the public demo allowlist):
//
//	GET    /vocabulary?q=           the saved terms (vocabulary_v1), searched and sorted
//	PUT    /vocabulary/{concept_id} {"unit_id": N}: save the Concept with that example
//	DELETE /vocabulary/{concept_id} remove it from the saved list (history kept)
//
// The saved term is a Concept (its durable identity), the example an approved
// unit currently supporting it. Saving again changes nothing; removing twice is
// safe. Errors: 400 bad input, 404 unknown Concept or unit (or never saved, on
// DELETE), 409 not savable with a reason code, 503 when not wired.

// VocabularyService is the transport's view of application.VocabularyService.
type VocabularyService interface {
	List(ctx context.Context, q string) (*application.VocabularyList, error)
	Save(ctx context.Context, conceptID, unitID int64) (*application.VocabularyItem, bool, bool, error)
	Remove(ctx context.Context, conceptID int64) (domain.VocabularyMark, bool, error)
}

// WithVocabulary enables the private /vocabulary routes. Without it they
// answer 503.
func WithVocabulary(service VocabularyService) HandlerOption {
	return func(handler *Handler) { handler.vocabulary = service }
}

func (h *Handler) registerVocabularyRoutes(mux *http.ServeMux) {
	mux.HandleFunc("GET /vocabulary", h.handleListVocabulary)
	mux.HandleFunc("PUT /vocabulary/{concept_id}", h.handleSaveVocabulary)
	mux.HandleFunc("DELETE /vocabulary/{concept_id}", h.handleRemoveVocabulary)
}

type vocabularyConceptJSON struct {
	ID                int64             `json:"id"`
	Target            string            `json:"target"`
	PedagogicalIntent string            `json:"pedagogical_intent"`
	Scope             string            `json:"scope"`
	IdentityFeatures  map[string]string `json:"identity_features"`
	State             string            `json:"state"`
}

type vocabularyExampleJSON struct {
	UnitID            int64  `json:"unit_id"`
	EntryID           int64  `json:"entry_id"`
	ExtractionID      int64  `json:"extraction_id"`
	ExtractionVersion int64  `json:"extraction_version"`
	SavedAt           string `json:"saved_at"`
	// current | not_current | missing
	Status          string `json:"status"`
	NewerExtraction bool   `json:"newer_extraction"`
	// Generated by the extraction (Extractor names who): the wording, the
	// meaning in each language (null: not recorded) and an example sentence.
	Term      *string                     `json:"term"`
	Kind      *string                     `json:"kind"`
	Meaning   *string                     `json:"meaning"`
	Meanings  explanationVariantsResponse `json:"meanings"`
	Sentence  *string                     `json:"sentence"`
	Extractor *string                     `json:"extractor"`
	// The learner's own record, exactly as written (null when unreadable).
	Source *vocabularySourceJSON `json:"source"`
}

type vocabularySourceJSON struct {
	EntryID         int64  `json:"entry_id"`
	OriginalInput   string `json:"original_input"`
	OriginalContext string `json:"original_context"`
	CreatedAt       string `json:"created_at"`
}

type vocabularyItemJSON struct {
	ConceptID    int64                   `json:"concept_id"`
	Saved        bool                    `json:"saved"`
	SavedAt      string                  `json:"saved_at"`
	FirstSavedAt string                  `json:"first_saved_at"`
	Concept      *vocabularyConceptJSON  `json:"concept"`
	ReviewUnits  int                     `json:"review_units"`
	Examples     []vocabularyExampleJSON `json:"examples"`
}

func strp(s string) *string { return &s }

func toVocabularyItem(it application.VocabularyItem) vocabularyItemJSON {
	out := vocabularyItemJSON{ConceptID: it.Mark.ConceptID, Saved: it.Mark.Saved, SavedAt: ts(it.Mark.At), FirstSavedAt: ts(it.Mark.FirstAt),
		ReviewUnits: it.ReviewUnits, Examples: []vocabularyExampleJSON{}}
	if c := it.Concept; c != nil {
		features := c.IdentityFeatures
		if features == nil {
			features = map[string]string{}
		}
		out.Concept = &vocabularyConceptJSON{ID: c.ID, Target: c.Target, PedagogicalIntent: c.PedagogicalIntent, Scope: c.Scope,
			IdentityFeatures: features, State: string(c.State)}
	}
	for _, e := range it.Examples {
		x := vocabularyExampleJSON{UnitID: e.Example.UnitID, EntryID: e.Example.EntryID, ExtractionID: e.Example.ExtractionID,
			ExtractionVersion: e.Example.ExtractionVersion, SavedAt: ts(e.Example.CreatedAt), Status: e.Status, NewerExtraction: e.NewerExtraction}
		if src := e.Source; src != nil {
			u := src.Unit.Unit
			x.Term, x.Kind, x.Meaning, x.Meanings, x.Sentence = strp(u.Canonical), strp(string(u.Kind)), strp(u.Statement), toVariants(u.Statements), u.Example
			x.Extractor = strp(src.Extraction.Extractor)
			x.Source = &vocabularySourceJSON{EntryID: src.Entry.ID, OriginalInput: src.Entry.OriginalInput, OriginalContext: src.Entry.OriginalContext,
				CreatedAt: ts(src.Entry.CreatedAt)}
		}
		out.Examples = append(out.Examples, x)
	}
	return out
}

func (h *Handler) vocabularyUnavailable(w http.ResponseWriter) bool {
	if h.vocabulary == nil {
		writeError(w, http.StatusServiceUnavailable, "vocabulary is not available on this server")
		return true
	}
	return false
}

func writeVocabularyError(w http.ResponseWriter, err error, action string) {
	var ns *domain.VocabularyNotSavableError
	switch {
	case errors.As(err, &ns):
		writeJSON(w, http.StatusConflict, map[string]string{"error": "this item cannot be saved as vocabulary: " + vocabularyReasonText[ns.Reason], "code": ns.Reason})
	case errors.Is(err, domain.ErrNotFound):
		writeError(w, http.StatusNotFound, "not found: the Concept or unit does not exist, or this Concept was never saved")
	case errors.Is(err, domain.ErrValidation), errors.Is(err, application.ErrVocabularyQuery):
		writeError(w, http.StatusBadRequest, err.Error())
	default:
		writeError(w, http.StatusInternalServerError, "could not "+action)
	}
}

var vocabularyReasonText = map[string]string{
	domain.VocabularyConceptRetired:    "the Concept is retired",
	domain.VocabularyNotVocabulary:     "the Concept is not a vocabulary Concept (its current support is not all vocabulary units)",
	domain.VocabularyUnitNotSupporting: "the unit does not currently support this Concept (pick an approved example)",
}

func parseConceptID(w http.ResponseWriter, r *http.Request) (int64, bool) {
	id, err := strconv.ParseInt(r.PathValue("concept_id"), 10, 64)
	if err != nil || id <= 0 {
		writeError(w, http.StatusBadRequest, "invalid concept id")
		return 0, false
	}
	return id, true
}

func (h *Handler) handleListVocabulary(w http.ResponseWriter, r *http.Request) {
	if h.vocabularyUnavailable(w) {
		return
	}
	list, err := h.vocabulary.List(r.Context(), r.URL.Query().Get("q"))
	if err != nil {
		writeVocabularyError(w, err, "read the vocabulary")
		return
	}
	items := make([]vocabularyItemJSON, 0, len(list.Items))
	for _, it := range list.Items {
		items = append(items, toVocabularyItem(it))
	}
	tokens := list.Tokens
	if tokens == nil {
		tokens = []string{}
	}
	writeJSON(w, http.StatusOK, map[string]any{"schema_version": domain.VocabularyVersion, "rule": application.ConceptLexicalNormalizationV1 + "; every query token a prefix",
		"query": list.Query, "tokens": tokens, "saved": list.Saved, "items": items})
}

func (h *Handler) handleSaveVocabulary(w http.ResponseWriter, r *http.Request) {
	if h.vocabularyUnavailable(w) {
		return
	}
	id, ok := parseConceptID(w, r)
	if !ok {
		return
	}
	var body struct {
		UnitID int64 `json:"unit_id"`
	}
	dec := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4096))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&body); err != nil || body.UnitID < 1 {
		writeError(w, http.StatusBadRequest, `the body must be {"unit_id": N} with the example's unit id`)
		return
	}
	it, saved, added, err := h.vocabulary.Save(r.Context(), id, body.UnitID)
	if err != nil {
		writeVocabularyError(w, err, "save the term")
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"item": toVocabularyItem(*it), "changed": saved || added, "saved_now": saved, "example_added": added})
}

func (h *Handler) handleRemoveVocabulary(w http.ResponseWriter, r *http.Request) {
	if h.vocabularyUnavailable(w) {
		return
	}
	id, ok := parseConceptID(w, r)
	if !ok {
		return
	}
	m, changed, err := h.vocabulary.Remove(r.Context(), id)
	if err != nil {
		writeVocabularyError(w, err, "remove the term")
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{"concept_id": id, "saved": m.Saved, "changed": changed})
}
